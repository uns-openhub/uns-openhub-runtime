-- ── trigger_definitions ───────────────────────────────────────────
-- Phase 6d (Trigger Service, Stage 1).  Reactive UNS data: when a
-- value matches a configured rule, publish a uns-kit message to a
-- new output topic.  Owned by the controller (auth-gated CRUD via
-- GraphQL); consumed by uns-api-global, which polls the
-- /api/triggers REST endpoint on boot + interval to keep its
-- in-process registry in sync.
--
-- Stage 1 supports three kinds:
--   high   — fire when value > config.threshold (edge-only)
--   low    — fire when value < config.threshold (edge-only)
--   event  — fire on value change, optionally filtered to
--            config.matchValues
-- Stage 2 adds: compare (cross-topic), string (specific match
-- with correlated reads).  Stage 3 adds the controller UI.
--
-- `config` is a JSON blob keyed off `kind`.  The resolver and the
-- consumer (uns-api-global) validate shape; Postgres just stores
-- it verbatim.
CREATE TABLE IF NOT EXISTS public."trigger_definitions" (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  kind text NOT NULL,
  "sourceTopic" text NOT NULL,
  "outputTopic" text NOT NULL,
  config jsonb NOT NULL DEFAULT '{}'::jsonb,
  "cooldownMs" integer NULL,
  enabled boolean NOT NULL DEFAULT true,
  description text NULL,
  "createdBy" text NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT trigger_definitions_kind_chk
    CHECK (kind IN ('high', 'low', 'event', 'compare', 'string', 'composite'))
);

-- Stage 4a + 5 — bring the existing constraint up to the latest
-- kind union when this script runs against a database that was
-- created before later kinds were added.  CREATE TABLE IF NOT
-- EXISTS skips the table when it exists, so the constraint update
-- needs to be its own statement.  The check looks for the newest
-- member ('composite') so the script is idempotent — re-runs
-- against an already-updated DB are no-ops.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'trigger_definitions_kind_chk'
      AND pg_get_constraintdef(oid) NOT LIKE '%composite%'
  ) THEN
    ALTER TABLE public."trigger_definitions"
      DROP CONSTRAINT trigger_definitions_kind_chk;
    ALTER TABLE public."trigger_definitions"
      ADD CONSTRAINT trigger_definitions_kind_chk
      CHECK (kind IN ('high', 'low', 'event', 'compare', 'string', 'composite'));
  END IF;
END$$;

